def compute_kde_contours(pts, level=0.7, gridsize=200):
    """
    Return seaborn-identical KDE contour, but as integer coordinates.
    Integer coords remain within the original pts' coordinate range.
    """
    data = np.asarray(pts).T
    if data.shape[1] < 5:
        return None
    try:
        kde = gaussian_kde(data)
    except np.linalg.LinAlgError:
        # Degenerate cell: its assigned spots are collinear or coincident, so the
        # 2D covariance is singular and gaussian_kde cannot be fit. Skip the
        # boundary for this cell (handled as a None contour downstream) instead
        # of aborting the whole run. Surfaces at large cell counts (e.g. WTA SCCC).
        return None
    x_min, y_min = pts.min(axis=0)
    x_max, y_max = pts.max(axis=0)
    x_pad = 0.05 * (x_max - x_min)
    y_pad = 0.05 * (y_max - y_min)
    xmin, xmax = x_min - x_pad, x_max + x_pad
    ymin, ymax = y_min - y_pad, y_max + y_pad
    # grid
    xi = np.linspace(xmin, xmax, gridsize)
    yi = np.linspace(ymin, ymax, gridsize)
    xx, yy = np.meshgrid(xi, yi)
    coords = np.vstack([xx.ravel(), yy.ravel()])
    # kde evaluate
    zz = kde(coords).reshape(gridsize, gridsize)
    # level threshold (seaborn logic)
    density_flat = zz.ravel()
    density_sorted = np.sort(density_flat)[::-1]
    cum_mass = np.cumsum(density_sorted)
    cum_mass /= cum_mass[-1]
    idx = np.searchsorted(cum_mass, level)
    contour_level = density_sorted[idx]
    # extract contour (matplotlib)
    fig, ax = plt.subplots()
    cs = ax.contour(xx, yy, zz, levels=[contour_level])
    paths = cs.get_paths()
    plt.close(fig)
    if len(paths) == 0:
        return None
    contour = max(paths, key=len)
    verts = contour.vertices  # (N,2) real coords
    # ----------- Convert to integer coords -----------
    # 1) map xy → grid index (float)
    col_idx = np.interp(verts[:, 0], xi, np.arange(gridsize))
    row_idx = np.interp(verts[:, 1], yi, np.arange(gridsize))
    # 2) round to integer grid
    col_int = np.round(col_idx).astype(int)
    row_int = np.round(row_idx).astype(int)
    # 3) map grid integer index → integer real coordinate
    x_int = np.interp(col_int, np.arange(gridsize), xi).astype(int)
    y_int = np.interp(row_int, np.arange(gridsize), yi).astype(int)
    # 4) ensure within original range
    x_int = np.clip(x_int, int(x_min), int(x_max))
    y_int = np.clip(y_int, int(y_min), int(y_max))
    integer_contour = np.column_stack([x_int, y_int])
    # 5) dedup
    integer_contour = np.unique(integer_contour, axis=0)
    return integer_contour

def get_cell_boundaries(cellist_seg_df, n_jobs):
    cellist_seg_df = cellist_seg_df.sort_values("Cellist")  
    groups = cellist_seg_df.groupby("Cellist")
    def process_one(label, df_cell):
        pts = df_cell[["x", "y"]].to_numpy()
        contour = compute_kde_contours(pts, level=0.75, gridsize=50)
        return label, contour
    results = Parallel(n_jobs=n_jobs)(
        delayed(process_one)(label, df_cell)
        for label, df_cell in groups
    )
    boundaries_dict = dict(results)
    rows = []
    for label, contour in boundaries_dict.items():
        if contour is None or len(contour) == 0:
            continue
        df = pd.DataFrame(contour, columns=["x", "y"])
        df["Cellist"] = label
        rows.append(df)
    boundaries_df = pd.concat(rows, ignore_index=True)
    boundaries_df = boundaries_df.sort_values(by = ['Cellist'])
    return boundaries_df

def _merge_slice_results(tmp_file_list_all):
    # Collect the per-slice soft-clustering tables and keep ONE assignment per spot: the one with
    # the highest probability over all overlapping slices / patches.
    # Deterministic by construction: files are read in sorted order and the per-spot choice is made
    # by sorting on (x_y, Cellist_prob, Cellist). Previously a first-occurrence
    # drop_duplicates(['x_y', 'Cellist']) ran BEFORE the probability sort, so when the same spot was
    # assigned to the same cell in several overlapping slices with different probabilities, the
    # copy that happened to be read first survived. The read order came from set iteration over
    # the thread/process pool results, so ~1% of labels changed between otherwise identical runs
    # (checked on E65: 357/357 slice files identical, 53,988 / 5.3M final labels different).
    # 'Cellist' as the last sort key only breaks exact probability ties; NaN probabilities (not
    # expected) sort first so they can never win.
    coord_df_sub_list = []
    for tmp_file in sorted(set(tmp_file_list_all)):
        if tmp_file != "NULL":
            coord_df_sub_list.append(pd.read_csv(tmp_file, sep = "\t"))
    coord_df_merge = pd.concat(coord_df_sub_list)
    coord_df_merge = coord_df_merge.dropna(subset = ['Cellist'])
    coord_df_merge = coord_df_merge.sort_values(by = ['x_y', 'Cellist_prob', 'Cellist'], na_position = 'first')
    coord_df_merge = coord_df_merge.drop_duplicates(subset = ['x_y'], keep = 'last')
    return coord_df_merge

AUTO_COUNT_LAYERS = ['EXONIC', 'INTRONIC', 'ExonCount', 'IntronCount']

def _resolve_count_columns(spot_expr_file, count_layers = None):
    # Read the GEM header (first non-'#' line) and decide which count columns to aggregate.
    #   count_name : the main count column = 4th GEM column, whichever name this SAW version
    #                wrote (MIDCount / MIDCounts). It is the only column the model uses.
    #   extra_cols : additional count columns (e.g. EXONIC / INTRONIC) aggregated into separate
    #                cell x gene matrices that share the gene / cell ordering of the main one.
    #     count_layers == ['auto'] (default) -> AUTO_COUNT_LAYERS that exist in the header
    #     count_layers == ['none'] or []     -> no extra layers
    #     otherwise                          -> the given names (missing ones skipped with a warning)
    with open(spot_expr_file) as f:
        for line in f:
            if not line.startswith('#'):
                header = line.rstrip('\n').split('\t')
                break
    count_name = header[3]
    if count_layers is None:
        count_layers = ['auto']
    count_layers = [str(c) for c in count_layers]
    if len(count_layers) == 0 or [c.lower() for c in count_layers] == ['none']:
        extra_cols = []
    elif [c.lower() for c in count_layers] == ['auto']:
        extra_cols = [c for c in AUTO_COUNT_LAYERS if c in header]
    else:
        missing = [c for c in count_layers if c not in header]
        if missing:
            logging.warning('--count-layers column(s) not found in the GEM header and skipped: %s' % ', '.join(missing))
        extra_cols = [c for c in count_layers if c in header]
    seen = set()
    extra_cols = [c for c in extra_cols if c != count_name and not (c in seen or seen.add(c))]
    return count_name, extra_cols

def _write_cell_count_h5_streaming(spot_expr_file, coord_map_df, out_prefix, out_dir, count_name = 'MIDCount', extra_cols = None):
    # Memory-bounded replacement for the merge's final cell x gene aggregation.
    # The original path loads the whole GEM (~1e9 rows, object geneID/x_y) into pandas and
    # pd.merge's it — that was the merge memory spike. Here we stream the GEM with polars,
    # join each spot to its assigned cell (coord_map_df: pandas x, y, Cellist) and sum
    # count_name per (cell, gene). Validated to reproduce the pandas get_cell_mat matrix
    # exactly (per-cell & per-gene sums bit-identical) at roughly 1/3 the peak RAM.
    # extra_cols (e.g. ['EXONIC', 'INTRONIC']) are summed in the SAME pass and written as
    # separate h5 files that share the gene order and cell barcode order of the main file,
    # so they can be loaded directly as layers of one matrix.
    import polars as pl
    from scipy.sparse import csc_matrix, coo_matrix
    extra_cols = [c for c in (extra_cols or []) if c != count_name]
    count_cols = [count_name] + extra_cols
    mapping = (pl.from_pandas(coord_map_df[['x', 'y', 'Cellist']])
                 .filter(pl.col('Cellist').is_not_null())
                 .with_columns([pl.col('x').cast(pl.Int32), pl.col('y').cast(pl.Int32),
                                pl.col('Cellist').cast(pl.Float64)]))
    agg = (pl.scan_csv(spot_expr_file, separator = '\t', comment_prefix = '#')
             .select(['x', 'y', 'geneID'] + count_cols)
             .with_columns([pl.col('x').cast(pl.Int32), pl.col('y').cast(pl.Int32)])
             .join(mapping.lazy(), on = ['x', 'y'], how = 'inner')
             .group_by(['Cellist', 'geneID'])
             .agg([pl.col(c).sum().alias(c) for c in count_cols])
             .collect(streaming = True))
    genes = sorted(agg['geneID'].unique().to_list())
    cells = sorted(agg['Cellist'].unique().to_list())
    gene_idx = pl.DataFrame({'geneID': genes, 'gi': np.arange(len(genes), dtype = np.int32)})
    cell_idx = pl.DataFrame({'Cellist': cells, 'ci': np.arange(len(cells), dtype = np.int32)})
    agg = (agg.join(gene_idx, on = 'geneID', how = 'left')
              .join(cell_idx, on = 'Cellist', how = 'left')
              .select(['gi', 'ci'] + count_cols))
    gi = agg['gi'].to_numpy()
    ci = agg['ci'].to_numpy()
    cell_barcodes = [str(float(c)) for c in cells]
    out_files = {}
    for col in count_cols:
        mat = csc_matrix(coo_matrix((agg[col].to_numpy().astype(np.float32), (gi, ci)),
            shape = (len(genes), len(cells))), dtype = np.float32)
        # The (cell, gene) pairs come from the main column; an extra layer (e.g. INTRONIC) is
        # zero on most of them, so drop explicit zeros to keep its h5 small.
        mat.eliminate_zeros()
        if col == count_name:
            out_file = os.path.join(out_dir, "%s_segmentation_cell_count.h5" %out_prefix)
        else:
            out_file = os.path.join(out_dir, "%s_segmentation_cell_count_%s.h5" %(out_prefix, col))
        write_10X_h5(filename = out_file, matrix = mat, features = genes, barcodes = cell_barcodes, datatype = 'Gene')
        out_files[col] = out_file
    return out_files

def _hvg_corr_spots_streaming(spot_expr_file, coord_map_df, hvg_list, count_name = 'MIDCount'):
    # Bounded-memory input builder for the nucleus-vs-cytoplasm correlation QC on the
    # streaming-merge path (where the full GEM is never loaded into pandas). Streams the GEM,
    # joins each spot to its assigned cell + nucleus flag (coord_map_df: x, y, Cellist, Nucleus),
    # keeps only HVG genes (~1k of ~19k, i.e. ~5% of rows) and pre-aggregates by
    # (Cellist, geneID, Nucleus). Pre-summing is safe: cal_corr_within_seg_nucleus splits by
    # Nucleus then groupby(Cellist, geneID).sum(), and sum-of-sums == sum. Returns a small
    # pandas frame with exactly the columns cal_corr_within_seg_nucleus expects.
    import polars as pl
    mapping = (pl.from_pandas(coord_map_df[['x', 'y', 'Cellist', 'Nucleus']])
                 .filter(pl.col('Cellist').is_not_null())
                 .with_columns([pl.col('x').cast(pl.Int32), pl.col('y').cast(pl.Int32),
                                pl.col('Cellist').cast(pl.Float64)]))
    agg = (pl.scan_csv(spot_expr_file, separator = '\t', comment_prefix = '#')
             .select(['x', 'y', 'geneID', count_name])
             .with_columns([pl.col('x').cast(pl.Int32), pl.col('y').cast(pl.Int32)])
             .join(mapping.lazy(), on = ['x', 'y'], how = 'inner')
             .filter(pl.col('geneID').is_in(list(hvg_list)))
             .group_by(['Cellist', 'geneID', 'Nucleus'])
             .agg(pl.col(count_name).sum().alias(count_name))
             .collect(streaming = True))
    return agg.to_pandas()

def _read_slice_write_patches(nucleus_seg_method, props_file, nucleus_count_h5_file, nucleus_coord_file,
    all_spot_count_h5_file, spot_expr_file, patch_size, stride_length, patch_data_dir, gene_use):
    # Runs in a DISPOSABLE child process (ProcessPoolExecutor max_workers=1): loads the full
    # input matrices, slices patches, writes them under patch_data_dir, and returns only the
    # (small) patch-prefix list. When the child exits, all loaded matrices are returned to the
    # OS — so the parent runs segmentation below with NO leftover full-matrix residual.
    # (CPython's del/gc.collect frees objects to its own pools but rarely back to the OS;
    #  only process exit does. Hence a child process instead of an in-process del.)
    logging.info('Reading input files...')
    count_df, coord_df, props_df, nucleus_expr_mat, nucleus_gene, nucleus_cell, all_count_mat, all_count_genes, all_count_spots = Read_files(
            nucleus_seg_method, props_file, nucleus_count_h5_file, nucleus_coord_file, all_spot_count_h5_file, spot_expr_file)
    # ----------- slice patches ----------
    coord_patch_list = slice_coord(coord_df, patch_size, stride_length)
    logging.info('There are %s patches to be processed!' %len(coord_patch_list))
    res_list = []
    with concurrent.futures.ThreadPoolExecutor(max_workers = 36) as executor:
        for i in range(len(coord_patch_list)):
            logging.info('Writing patch %s...' %i)
            xmin_patch, xmax_patch, ymin_patch, ymax_patch = coord_patch_list[i]
            arg_tuple = (count_df, coord_df, nucleus_seg_method, props_df, nucleus_expr_mat, nucleus_gene, nucleus_cell, all_count_mat, all_count_genes, all_count_spots,
            xmin_patch, xmax_patch, ymin_patch, ymax_patch,
            patch_data_dir, gene_use)
            res_list.append(executor.submit(Write_patch, *arg_tuple))
        done, not_done = concurrent.futures.wait(res_list, timeout=None)
        tmp_input_list_all = [future.result() for future in done]
    return [patch for patch in tmp_input_list_all if patch != 'NULL']

def Cellist(platform, resolution, nucleus_seg_method, props_file, nucleus_count_h5_file, nucleus_coord_file, all_spot_count_h5_file, spot_expr_file,
    patch_data_dir, num_workers,
    alpha, sigma, beta, gene_use, max_dist, two_step, cyto, max_dist_s1_scale, noise_prop_s1, noise_prop, neigh_dist, out_dir, out_prefix,
    min_nucleus_spots = 20,
    slice_size = None, slice_stride = None,
    count_layers = None):
    # ----------- output prefix ----------
    out_prefix = out_prefix + "_Cellist"
    if platform == 'barcoding':
        patch_size = 1100
        stride_length = 100
    elif platform == 'imaging':
        patch_size = 2200
        stride_length = 100
    if two_step:
        out_para = "alpha_%s_sigma_%s_beta_%s_gene_%s_dist_%s_twostep_%s_cyto_%s_noise_%s_neigh_%s_dscale_%s_s1noise_%s" %(alpha, sigma, beta, gene_use, max_dist, two_step, cyto, noise_prop, neigh_dist, max_dist_s1_scale, noise_prop_s1)
    else:
        out_para = "alpha_%s_sigma_%s_beta_%s_gene_%s_dist_%s_twostep_%s_cyto_%s_noise_%s_neigh_%s" %(alpha, sigma, beta, gene_use, max_dist, two_step, cyto, noise_prop, neigh_dist)
    out_dir = os.path.join(out_dir, out_para)
    if not os.path.exists(out_dir):
        os.makedirs(out_dir)
    tmp_dir = os.path.join(out_dir, "tmp")
    if not os.path.exists(tmp_dir):
        os.makedirs(tmp_dir)
    # -------------- write tmp patch files -------------
    if patch_data_dir:
        patch_prefix_list = []
        for patch_file in os.listdir(patch_data_dir):
            if patch_file.endswith('_spot_count.h5'):
                patch_prefix = patch_file.split('_spot_count.h5')[0]
                patch_prefix_list.append(patch_prefix)
    else:
        # Create the patch dir in the parent, then do the heavy "read full input + write
        # patches" work in ONE disposable child process. When it exits, all loaded matrices
        # are released to the OS, so segmentation below has no full-matrix residual. This makes
        # the single `cellist seg` command equivalent to a manual two-stage run, automatically.
        patch_data_dir = os.path.join(out_dir, "..", "Data_%s" %gene_use)
        if not os.path.exists(patch_data_dir):
            os.mkdir(patch_data_dir)
        logging.info('Reading input + writing patches in a disposable child process '
            '(memory is returned to the OS before segmentation)...')
        with concurrent.futures.ProcessPoolExecutor(max_workers = 1) as patch_executor:
            patch_prefix_list = patch_executor.submit(_read_slice_write_patches,
                nucleus_seg_method, props_file, nucleus_count_h5_file, nucleus_coord_file,
                all_spot_count_h5_file, spot_expr_file, patch_size, stride_length,
                patch_data_dir, gene_use).result()
        gc.collect()
    # ----------- segmentation ----------
    patch_prefix_list = sorted(patch_prefix_list)
    logging.info('Start segmentation...')
    patch_res_list = []
    tmp_file_list_all = []
    with concurrent.futures.ProcessPoolExecutor(max_workers = num_workers) as executor_patch:
        for i in range(len(patch_prefix_list)):
            patch_prefix = patch_prefix_list[i]
            logging.info('Processing patch %s...' %patch_prefix)
            props_file_patch = os.path.join(patch_data_dir, "%s_property.txt" %patch_prefix)
            coord_file_patch = os.path.join(patch_data_dir, "%s_coord.txt" %patch_prefix)
            all_spot_count_h5_file_patch = os.path.join(patch_data_dir, "%s_spot_count.h5" %patch_prefix)
            count_file_patch = os.path.join(patch_data_dir, "%s_count.txt" %patch_prefix)
            arg_tuple_patch = (platform, resolution, nucleus_seg_method, props_file_patch, coord_file_patch, all_spot_count_h5_file_patch, count_file_patch,
                out_dir, num_workers,
                alpha, sigma, beta, gene_use, max_dist, two_step, cyto, max_dist_s1_scale, noise_prop_s1, noise_prop, neigh_dist,
                min_nucleus_spots,
                slice_size, slice_stride)
            patch_res_list.append(executor_patch.submit(Soft_assignment_patch, *arg_tuple_patch))
        done_patch, not_done_patch = concurrent.futures.wait(patch_res_list, timeout=None)
        for future in done_patch:
            tmp_file_list_all = tmp_file_list_all + future.result()
    # ------------ merge results from patches ------------
    logging.info('Merging results from patches...')
    # When polars is available, aggregate the final cell x gene matrix by streaming the GEM
    # (see below) instead of loading its ~1e9 rows into pandas + pd.merge — that load was the
    # merge memory spike. Fall back to the original pandas path if polars is missing.
    try:
        import polars as _pl
        stream_merge = True
    except Exception:
        stream_merge = False
    count_df, coord_df, _, nucleus_expr_mat, nucleus_gene, nucleus_cell, _, _, _ = Read_files(
            nucleus_seg_method, props_file, nucleus_count_h5_file, nucleus_coord_file, all_spot_count_h5_file, spot_expr_file,
            load_count = not stream_merge)
    coord_df_merge = _merge_slice_results(tmp_file_list_all)
    # coord_df_merge = pd.merge(coord_df, coord_df_merge[['x_y', 'Cellist', 'Cellist_prob', 'Cellist_norm', 'Cellist_prob_norm', 'Cellist_slice']], how = "left", on = "x_y")
    coord_df_merge = pd.merge(coord_df, coord_df_merge[['x_y', 'Cellist', 'Cellist_prob', 'Cellist_norm', 'Cellist_prob_norm']], how = "left", on = "x_y")
    coord_df_merge = Assign_filter(coord_df_merge, out_dir, out_prefix, noise_prop)
    logging.info('Writing segmentation results...')
    coord_df_merge.to_csv(os.path.join(out_dir, "%s_segmentation.txt" %(out_prefix)), sep = "\t", index = False)
    boundaries_df = get_cell_boundaries(coord_df_merge[['x','y','Cellist']], num_workers)
    boundaries_df.to_csv(os.path.join(out_dir, "%s_segmentation_cell_boundary_coord.txt" %(out_prefix)), sep = "\t", index = False)
    draw_segmentation(coord_df_sub = coord_df_merge, seg_res = "Cellist", out_prefix = out_prefix, 
    out_dir = out_dir, x = "x", y = "y", figsize = (80, 80))
    # Detect the count column name from the GEM header (4th column) instead of
    # hardcoding 'MIDCount': SAW versions emit either 'MIDCount' or 'MIDCounts'.
    # Also resolve the extra count layers (e.g. EXONIC / INTRONIC) requested via --count-layers;
    # they are aggregated in the same pass and written as *_segmentation_cell_count_{COLUMN}.h5.
    count_name, extra_count_cols = _resolve_count_columns(spot_expr_file, count_layers)
    if extra_count_cols:
        logging.info('Extra cell-level count layers to aggregate: %s' % ', '.join(extra_count_cols))
    if stream_merge:
        # Bounded-memory aggregation: stream GEM -> join x,y -> Cellist -> sum per (cell, gene).
        _write_cell_count_h5_streaming(spot_expr_file, coord_df_merge[['x', 'y', 'Cellist']], out_prefix, out_dir, count_name,
            extra_cols = extra_count_cols)
    else:
        count_df = pd.merge(count_df, coord_df_merge[['x_y', 'Cellist', 'Nucleus']], how = "left", on = "x_y")
        write_segmentation_h5(count_df, "Cellist", out_prefix, out_dir, count_name, extra_cols = extra_count_cols)
    write_segmentation_cell_coord(coord_df_merge, "Cellist", out_prefix, out_dir)
    logging.info('Writing parameters and basic cell statistics...')
    hvg_list = get_hvg(nucleus_expr_mat, nucleus_gene, nucleus_cell, 1000)
    cell_num = coord_df_merge['Cellist'].value_counts().shape[0]
    nspot_all = int(coord_df_merge['Cellist'].count())
    nspot_nucleus = int(coord_df_merge[nucleus_seg_method].count())
    nspot_avg = int(nspot_all/cell_num)
    para_dict = {
        'nucleus_seg_method': nucleus_seg_method,
        'props_file': props_file, 
        'nucleus_count_h5_file': nucleus_count_h5_file, 
        'nucleus_coord_file': nucleus_coord_file, 
        'all_spot_count_h5_file': all_spot_count_h5_file, 
        'spot_expr_file': spot_expr_file, 
        'num_workers': num_workers, 
        'alpha': alpha, 
        'sigma': sigma, 
        'beta': beta, 
        'gene_use': gene_use, 
        'max_dist': max_dist, 
        'two_step': two_step,
        'noise_prop': noise_prop,
        'count_name': count_name,
        'count_layers': count_layers,
        'extra_count_layers': extra_count_cols,
        'cell_num': cell_num,
        'nspot_nucleus': nspot_nucleus,
        'nspot_all': nspot_all,
        'nspot_avg': nspot_avg
    }
    try:
        if count_df is None:
            # streaming merge path: the full GEM was never loaded into pandas. Build a small
            # HVG-only per-(cell, gene, nucleus) table by streaming the GEM, so the
            # nucleus-vs-cytoplasm correlation QC still runs in bounded memory.
            corr_count_df = _hvg_corr_spots_streaming(
                spot_expr_file, coord_df_merge[['x', 'y', 'Cellist', 'Nucleus']], hvg_list, count_name)
        else:
            corr_count_df = count_df
        if len(nucleus_cell) > 100000:
            seed(0)
            cells_sample = sample(nucleus_cell, 100000)
            Cellist_corr_nucl_cyto, Cellist_corr_nucl_cyto_cell = cal_corr_within_seg_nucleus(corr_count_df.loc[corr_count_df['Cellist'].isin(cells_sample), :], "Cellist", hvg_list, count_name)
        else:
            Cellist_corr_nucl_cyto, Cellist_corr_nucl_cyto_cell = cal_corr_within_seg_nucleus(corr_count_df, "Cellist", hvg_list, count_name)
        Cellist_corr_nucl_cyto_df = pd.DataFrame({'Cell': Cellist_corr_nucl_cyto_cell, 'Correlation': Cellist_corr_nucl_cyto})
        Cellist_corr_nucl_cyto_df.to_csv(os.path.join(out_dir, "%s_corr_nucl_cyto_df.txt" %out_prefix), index = False, sep = "\t")
        # statics
        para_dict['Correlation'] = np.nanquantile(Cellist_corr_nucl_cyto, [0, 0.25, 0.5, 0.75, 1]).tolist()
    except Exception as e:
        # don't fail the whole run for an optional QC, but surface why (was silently swallowed)
        logging.warning('Nucleus-vs-cytoplasm correlation QC skipped: %s' % e)
        # write parameters
    with open(os.path.join(out_dir, "parameters.json"), "w") as outfile:
        json.dump(para_dict, outfile)

